import re, sys

src = open(sys.argv[1], encoding='utf-8').read()
root = src[src.index("static struct insn tabroot[]"):]
root = root[: root.index("\n};")]
rows = []
for line in root.splitlines():
    m = re.search(r'\{ 0x([0-9a-f]+)ull, 0x([0-9a-f]+)ull, OP8B,[^N]*N\(\s*"([\w.]+)"\)', line)
    if not m:
        continue
    value, mask, name = int(m.group(1), 16), int(m.group(2), 16), m.group(3)
    form = "reg"
    if re.search(r"C34_RZ_O14_20|C36_RZ_S16_20|C36_08_S16_20", line):
        form = "cbuf"
    elif re.search(r"\b(S20_20|F20_20|D20_20|U20_20|S32_20|F32_20|U32_20|U16_20|S16_20|U13_36|U24_20|S24_20|U12_20|U05_20|U08_20|U06_20|S11_20)\b", line):
        form = "imm"
    rows.append((value, mask, name, form))

out = sys.argv[2]
