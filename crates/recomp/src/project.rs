use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Instant;

use kirikae_loader::package::{from_source, pack, Source};
use kirikae_loader::{dynamic, Executable};

use crate::clif;
use crate::discover::{discover, find_entries, CodeSpace};
use crate::rust_backend::emit_program;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Backend {
    Rust,
    Cranelift,
}

pub struct BuildOptions {
    pub out_dir: PathBuf,
    pub name: String,
    pub target_dir: Option<PathBuf>,
    pub backend: Backend,
    pub jobs: usize,
    pub fast_regs: bool,
    pub profile: Option<PathBuf>,
    pub plugins: Vec<PathBuf>,
}

impl BuildOptions {
    pub fn new(out_dir: impl Into<PathBuf>, name: &str) -> BuildOptions {
        BuildOptions {
            out_dir: out_dir.into(),
            name: name.into(),
            target_dir: None,
            backend: Backend::Cranelift,
            jobs: std::thread::available_parallelism().map_or(4, |n| n.get()),
            fast_regs: false,
            profile: None,
            plugins: Vec::new(),
        }
    }
}

pub struct BuildReport {
    pub executable: PathBuf,
    pub functions: usize,
    pub instructions: u64,
    pub reachable: u64,
    pub total: u64,
}

const FUNCTIONS_PER_OBJECT: usize = 1024;

pub fn runtime_path() -> PathBuf {
    if let Some(dir) = std::env::var_os("KIRIKAE_RUNTIME") {
        return PathBuf::from(dir);
    }
    let bundled = std::env::current_exe().ok().and_then(|e| e.parent().map(|d| d.join("runtime").join("crates").join("rt")));
    match bundled {
        Some(rt) if rt.join("Cargo.toml").is_file() => rt,
        _ => Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("rt"),
    }
}

pub fn package_name(name: &str) -> String {
    let mut s: String = name
        .chars()
        .map(|ch| if ch.is_ascii_alphanumeric() { ch.to_ascii_lowercase() } else { '-' })
        .collect();
    while s.contains("--") {
        s = s.replace("--", "-");
    }
    s = s.trim_matches('-').to_string();
    if !s.starts_with(|ch: char| ch.is_ascii_lowercase()) {
        s.insert_str(0, "game-");
    }
    s
}

fn toml_path(p: &Path) -> String {
    p.display().to_string().replace('\\', "/")
}

fn plugin_name(dir: &Path) -> Result<String, String> {
    let manifest = dir.join("Cargo.toml");
    let text = fs::read_to_string(&manifest).map_err(|e| format!("{}: {e}", manifest.display()))?;
    text.lines()
        .skip_while(|l| l.trim() != "[package]")
        .find_map(|l| l.trim().strip_prefix("name").map(|v| v.trim_start_matches([' ', '=']).trim().trim_matches('"').to_string()))
        .ok_or_else(|| format!("{}: no package name", manifest.display()))
}

fn manifest(name: &str, build_script: bool, plugins: &[(String, PathBuf)]) -> String {
    let rt = toml_path(&runtime_path());
    let build = if build_script { "build = \"build.rs\"\n" } else { "" };
    let extra: String = plugins.iter().map(|(n, p)| format!("{n} = {{ path = '{}' }}\n", toml_path(p))).collect();
    format!(
        "[package]\n\
         name = \"{name}\"\n\
         version = \"0.1.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         {build}\n\
         [dependencies]\n\
         kirikae-rt = {{ path = '{rt}' }}\n\
         {extra}\n\
         [profile.release]\n\
         opt-level = 3\n\
         debug = false\n\n\
         # Not part of any enclosing workspace.\n\
         [workspace]\n"
    )
}

const CLIF_MAIN: &str = "\
// Generated by kirikae. Do not edit: rerun `kirikae build` instead.

static PACKAGE: &[u8] = include_bytes!(\"package.bin\");

unsafe extern \"C\" {
    static kirikae_entries: kirikae_rt::Entry;
    static kirikae_entry_count: u64;
}

fn main() {
    // SAFETY: the table and its length come from the same generated object.
    let entries = unsafe { std::slice::from_raw_parts(&raw const kirikae_entries, kirikae_entry_count as usize) };
@PLUGINS@    kirikae_rt::program_main(PACKAGE, entries)
}
";

const CLIF_BUILD_RS: &str = "\
// Generated by kirikae: link the recompiled guest code.
fn main() {
    let list = std::fs::read_to_string(\"objects.txt\").expect(\"objects.txt\");
    for obj in list.lines().filter(|l| !l.is_empty()) {
        println!(\"cargo:rustc-link-arg-bins={obj}\");
    }
    println!(\"cargo:rerun-if-changed=objects.txt\");
}
";

fn write(path: PathBuf, bytes: &[u8]) -> Result<(), String> {
    fs::write(&path, bytes).map_err(|e| format!("{}: {e}", path.display()))
}

pub fn seeds(exe: &Executable) -> Vec<u64> {
    let mut s = Vec::new();
    for m in &exe.modules {
        s.push(m.image.entry);
        s.extend(dynamic::code_pointers(&m.image));
    }
    s
}

pub fn build(source: &Source, opts: &BuildOptions) -> Result<BuildReport, String> {
    let exe = from_source(source).map_err(|e| e.to_string())?;
    let name = package_name(&opts.name);
    let mut plugins = Vec::new();
    for dir in &opts.plugins {
        let dir = std::path::absolute(dir).map_err(|e| e.to_string())?;
        plugins.push((plugin_name(&dir)?, dir));
    }
    if !plugins.is_empty() && opts.backend != Backend::Cranelift {
        return Err("plugins need the Cranelift backend".into());
    }
    let out_dir = std::path::absolute(&opts.out_dir).map_err(|e| e.to_string())?;
    let project = out_dir.join(format!("{name}-build"));
    let src = project.join("src");
    fs::create_dir_all(&src).map_err(|e| format!("{}: {e}", src.display()))?;
    write(src.join("package.bin"), &pack(source))?;

    let report = match opts.backend {
        Backend::Rust => {
            let [module] = exe.modules.as_slice() else {
                return Err("the Rust backend handles single-module programs; use the Cranelift backend".into());
            };
            let prog = discover(&module.image);
            write(project.join("Cargo.toml"), manifest(&name, false, &[]).as_bytes())?;
            write(src.join("main.rs"), emit_program(&prog, "package.bin").as_bytes())?;
            let instructions = prog.functions.iter().map(|f| f.insn_count() as u64).sum();
            (prog.functions.len(), instructions, instructions, (module.image.text.end - module.image.text.start) / 4)
        }
        Backend::Cranelift => {
            let space = CodeSpace::new(exe.modules.iter().map(|m| &m.image).collect());
            let t0 = Instant::now();
            let mut roots = seeds(&exe);
            let profile = opts.profile.clone().unwrap_or_else(|| out_dir.join(format!("{name}.profile")));
            match fs::read_to_string(&profile) {
                Ok(text) => {
                    let extra: Vec<u64> = kirikae_rt::coverage::parse(&text).into_iter().map(|(a, _)| a).filter(|&a| space.is_code(a)).collect();
                    eprintln!("kirikae: {} interpreted addresses from {} become functions", extra.len(), profile.display());
                    roots.extend(extra);
                }
                Err(e) if opts.profile.is_some() => return Err(format!("{}: {e}", profile.display())),
                Err(_) => {}
            }
            let (entries, reachable) = find_entries(&space, &roots);
            eprintln!(
                "kirikae: {} functions, {reachable} of {} instructions reachable ({:.1}s)",
                entries.len(),
                space.words(),
                t0.elapsed().as_secs_f64()
            );
            let t1 = Instant::now();
            let progress = |done: usize, total: usize| {
                if done == total || done.is_multiple_of(16) {
                    eprintln!("kirikae: code generation {done}/{total} objects");
                }
            };
            let rep = clif::compile_program(&space, &entries, &project.join("obj"), FUNCTIONS_PER_OBJECT, opts.jobs, opts.fast_regs, &progress)?;
            eprintln!("kirikae: generated {} instructions in {:.1}s", rep.instructions, t1.elapsed().as_secs_f64());
            let list: String = rep.objects.iter().map(|o| format!("{}\n", o.display())).collect();
            write(project.join("objects.txt"), list.as_bytes())?;
            write(project.join("build.rs"), CLIF_BUILD_RS.as_bytes())?;
            write(project.join("Cargo.toml"), manifest(&name, true, &plugins).as_bytes())?;
            let installs: String = plugins.iter().map(|(n, _)| format!("    {}::install();\n", n.replace('-', "_"))).collect();
            write(src.join("main.rs"), CLIF_MAIN.replace("@PLUGINS@", &installs).as_bytes())?;
            (rep.functions, rep.instructions, reachable, space.words())
        }
    };

    let target_dir = opts.target_dir.clone().unwrap_or_else(|| match std::env::var_os("CARGO_TARGET_DIR") {
        Some(dir) => PathBuf::from(dir).join("kirikae-games"),
        None => project.join("target"),
    });
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let status = Command::new(cargo)
        .arg("build")
        .arg("--release")
        .arg("--manifest-path")
        .arg(project.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target_dir)
        .status()
        .map_err(|e| format!("could not run cargo: {e}"))?;
    if !status.success() {
        return Err(format!("cargo build failed ({status})"));
    }

    let exe_name = format!("{name}{}", std::env::consts::EXE_SUFFIX);
    let built = target_dir.join("release").join(&exe_name);
    let executable = out_dir.join(&exe_name);
    fs::copy(&built, &executable).map_err(|e| format!("copying {}: {e}", built.display()))?;
    let (functions, instructions, reachable, total) = report;
    Ok(BuildReport { executable, functions, instructions, reachable, total })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn package_names() {
        assert_eq!(package_name("Hello World"), "hello-world");
        assert_eq!(package_name("0100ABCD"), "game-0100abcd");
        assert_eq!(package_name("hello.nro"), "hello-nro");
        assert_eq!(package_name("My Homebrew: Demo"), "my-homebrew-demo");
    }
}
